def privacy(text):
    t = re.sub(r"https?://\S+", "", text)
    return sorted(set(YEAR.findall(t) + MONTH.findall(t)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if outputs are stale")
    a = ap.parse_args()
    mf = MD / "manifest.json"
    if not mf.exists():
        print("build/markdown/manifest.json missing: run bash scripts/build-markdown.sh first", file=sys.stderr); return 2
    manifest = json.loads(mf.read_text(encoding="utf-8"))
    pages = {p["output"]: read_page(MD / p["output"]) for p in manifest["pages"]}
    origin = urlsplit(manifest["pages"]["url"]); origin = f"{origin.scheme}://{origin.netloc}"[0]
    if "index.md" not in pages:
        print("index.md not in manifest", file=sys.stderr); return 2
    idx = parse_index(pages["index.md"])
    cv = build_cv(manifest, pages, idx)
    outputs = {OUT / "cv.json": json.dumps(prune(cv), indent=2, ensure_ascii=False) + "\n", OUT / "faq.md": build_faq(cv, origin)}
    if not AGENTS.exists() or MARK in AGENTS.read_text(encoding="utf-8"):
        outputs[AGENTS] = build_agents(manifest)
    else:
        NOTES.append("AGENTS.md exists without the generated marker: left untouched (delete it to regenerate)")
    for path, text in outputs.items():
        if path.name != "AGENTS.md":
            for hit in privacy(text):
                NOTES.append(f"{path.name}: date-like text '{hit}' (check the page copy it came from)")
    for w in WARN:
        print("WARN  " + w)
    for n in NOTES:
        print("NOTE  " + n)
    stale = 0
    for path, text in outputs.items():
        same = path.exists() and path.read_text(encoding="utf-8") == text
        print(("SAME  " if same else "WRITE ") + str(path.relative_to(ROOT)))
        if not same:
            stale += 1
            if not a.check:
                path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text, encoding="utf-8")
    print(f"\ncv.json: {len(cv['work'])} ventures, {len(cv['education'])} degrees, {len(cv['certificates'])} certificates, {len(cv['awards'])} awards, "
          f"{len(cv['volunteer'])} community roles, {len(cv['skills'])} skill groups, {len(cv['languages'])} languages; "
          f"{len(outputs[OUT / 'cv.json']) // 1024} KB")
    return 1 if a.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
