def sentence_list(items, n=None):
    items = [i for i in items if i][:n] if n else [i for i in items if i]
    return ", ".join(items[:-1]) + (" and " if len(items) > 1 else "") + items[-1] if items else ""


def prune(o):
    if isinstance(o, dict):
        return {k: v for k, v in ((k, prune(v)) for k, v in o.items()) if v not in ("", [], {}, None)}
    if isinstance(o, list):
        return [v for v in (prune(x) for x in o) if v not in ("", [], {}, None)]
    return o


def build_faq(cv, origin):
    b, qa = cv["basics"], []
    w = {x["name"].lower(): x for x in cv["work"]}
    q = lambda question, answer: qa.append((question, answer)) if answer else WARN.append("faq: no data for '" + question + "'")
    q("Who is George Dreemer?", b["summary"])
    code = cv["skills"]["keywords"] if cv["skills"] else [][0]
    libs = next((s["keywords"] for s in cv["skills"] if s["name"].lower().startswith("python lib")), [])
    q("What is his technical stack?", f"Languages: {sentence_list(code)}. Python libraries: {sentence_list(libs[:8])}, among others. Full groups are in [cv.json]({origin}/cv.json).")
    ds = w.get("datasafari")
    if ds:
        nums = "; ".join(f"{m['value']} {m['label'].lower()}" for m in ds["x-metrics"][:5])
        q("What is DataSafari?", f"{ds['summary']} Role: {ds['position']}. Key numbers: {nums}. Links: " + ", ".join(f"[{l['label']}]({l['url']})" for l in ds["x-links"]) + f". Details: [{ds['name']}]({ds['x-markdown']}).")
    q("What has he built or founded?", "\n".join(f"- **{x['name']}** ({x['position']}): {x['summary']} [{x['x-markdown'].rsplit('/', 1)[-1]}]({x['x-markdown']})" for x in cv["work"]))
    q("What are his strongest data science credentials?", "\n".join(
        [f"- {e['area']} ({e['studyType']}), {e['institution']}" + (f", {e.get('x-score-label', 'result').lower()} {e['score']}" if e["score"] else "") for e in cv["education"] if re.search(r"data|analytic|statist|machine", e["area"] + " " + " ".join(e["courses"]), re.I)]
        + [f"- {c['name']} ({c['issuer']})" for c in cv["certificates"] if "data scientist" in c["name"].lower()]))
    q("Where did he study?", "\n".join(f"- {e['institution']}: {e['area']} ({e['studyType']}). Topics: {sentence_list(e['courses'][:6])}. [{e['url'].rsplit('/', 1)[-1]}]({e['x-markdown']})" for e in cv["education"]))
    q("Which languages does he speak?", sentence_list([f"{l['language']} ({l['fluency']})" if l["fluency"] else l["language"] for l in cv["languages"]]) + ". Levels follow the CEFR scale as stated on the site.")
    q("Which certificates does he hold?", "\n".join(f"- {c['name']} — {c['issuer']}" + (f" ([verify]({c['url']}))" if c["url"] else "") for c in cv["certificates"]))
    q("What awards has he won?", "\n".join(f"- {a['title']} — {a['awarder']}" + (f" ([certificate]({a['url']}))" if a["url"] else "") for a in cv["awards"]))
    q("What community and leadership roles has he held?", "\n".join(f"- {v['organization']}: {v['position']}" for v in cv["volunteer"]))
    cp = w.get("cryptopandemic")
    if cp:
        q("Does he have Web3 experience?", f"{cp['summary']} Role: {cp['position']}. Capabilities: {sentence_list(cp['x-capabilities'])}. [{cp['name']}]({cp['x-markdown']}).")
    dc = w.get("dreemcorp")
    if dc:
        q("What creative and content-production experience does he have?", f"{dc['summary']} Role: {dc['position']}. Numbers: " + "; ".join(f"{m['value']} {m['label'].lower()}" for m in dc["x-metrics"][:4]) + f". [{dc['name']}]({dc['x-markdown']}).")
    code_links = [f"- {p['network']}: {p['url']}" for p in b["profiles"] if p["network"] == "GitHub"]
    code_links += [f"- {x['name']} — {l['label']}: {l['url']}" for x in cv["work"] for l in x.get("x-links", []) if l["label"].lower() in ("github", "docs", "pypi")]
    q("Where can I see his code and technical work?", "\n".join(code_links))
    ch = b.get("x-contact", {}).get("channels", {})
    q("How can I contact him?", "Email, phone and location are not published on this site. " + " ".join(f"{k}: {v['url']} — {v['note']}" for k, v in ch.items()))
    q("What are his availability, salary expectations, notice period and visa status?", "These are not published on the site, so they are unknown here. Please ask him directly through the channels above.")
    naming = next((l[2:].strip() for l in LLMS.read_text(encoding="utf-8").splitlines() if l.startswith("- Call him")), "") if LLMS.exists() else ""
    q("How should he be addressed?", naming)
    out = ["# Recruiter FAQ — George Dreemer", "", f"> Answers generated from the site's own pages ({origin}). Nothing here is added from outside the site. Source of truth: [llms-full.txt]({origin}/llms-full.txt).", ""]
    for question, answer in qa:
        out += [f"## {question}", "", answer, ""]
    return "\n".join(out).rstrip() + "\n"


