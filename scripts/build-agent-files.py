"""build-agent-files.py - generate cv.json, faq.md and AGENTS.md from the finished site files.

Reads  : build/markdown/manifest.json + *.md   (from build-markdown.sh)
         seo/schema/index_schema.json          (Person: title, profiles)
         seo/llms.txt                          (contact / naming guidance)
Writes : build/agent/cv.json, build/agent/faq.md      (publish at the site root)
         AGENTS.md                                    (repo root; never overwrites a hand-edited file)

Nothing is invented: every value comes from your pages. Dates, contact details, salary,
visa status are NOT on the site, so they are NOT in the output (they belong in your private CV file).

  python3 scripts/build-agent-files.py            # build
  python3 scripts/build-agent-files.py --check    # write nothing; exit 1 if outputs are stale
Standard library only.
"""
