#!/usr/bin/env python3
"""build-llms.py: validate seo/llms.txt and build llms-full.txt + deploy snippets.

Reads  : seo/llms.txt (hand-written), build/markdown/manifest.json + *.md (from build-markdown)
Writes : build/markdown/llms.txt, build/markdown/llms-full.txt   (publish these)
         build/reports/htaccess-markdown.conf, build/reports/head-links.txt   (copy/paste once)
Stdlib only:  python3 scripts/build-llms.py   [--check]
"""

import argparse
import json
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
MD_DIR, SRC, REPORTS = (
    ROOT / "build" / "markdown",
    ROOT / "seo" / "llms.txt",
    ROOT / "build" / "reports",
)
YEAR = re.compile(r"\b(?:19|20)\d{2}\b")
MONTH = re.compile(
    r"\b(?:January|February|March|April|June|July|August|September|October|November|December)\b"
    r"|\bMay\s+\d{1,2}\b|\b\d{1,2}\s+May\b"
)
FORBIDDEN = []  # extra private strings that must never appear, e.g. ["Springfield"]
EXTRA_INTERNAL = {
    "llms-full.txt",
    "downloads/",
}  # internal paths allowed in llms.txt besides page .md files
MAX_WORDS = 900


def split_front(text):
    m = re.match(r"---\n.*?\n---\n\n?", text, re.DOTALL)
    return text[m.end() :] if m else text


def privacy_hits(text):
    return sorted(
        set(
            YEAR.findall(text)
            + MONTH.findall(text)
            + [f for f in FORBIDDEN if f.lower() in text.lower()]
        )
    )


def validate(text, pages, origin):
    errs, warns = [], []
    lines = text.splitlines()
    if not lines or not re.match(r"# \S", lines[0]):
        errs.append("line 1 must be '# Site name' (the only required element)")
    if sum(1 for l in lines if re.match(r"# ", l)) != 1:
        errs.append("exactly one H1 allowed")
    if not any(l.startswith("> ") for l in lines[:6]):
        errs.append("add a '> summary' blockquote right after the H1")
    h2 = False
    for n, l in enumerate(lines, 1):
        if re.match(r"##+ ", l) and not l.startswith("## "):
            errs.append(f"line {n}: only H2 headings allowed")
        if l.startswith("## "):
            h2 = True
        elif h2 and l.strip() and not re.match(r"- \[[^\]]+\]\(\S+\)(: .+)?$", l):
            errs.append(f"line {n}: file lists need '- [name](url): note'")
    allowed = {p["markdown_url"] for p in pages} | {
        origin + "/" + e for e in EXTRA_INTERNAL
    }
    linked = set()
    for url in re.findall(r"\]\((\S+?)\)", text):
        linked.add(url)
        if url.startswith(origin) and not any(
            url == a or (a.endswith("/") and url.startswith(a)) for a in allowed
        ):
            errs.append("internal link not in manifest (typo or page removed): " + url)
    for p in pages:
        if p["markdown_url"] not in linked:
            errs.append("page missing from llms.txt: " + p["markdown_url"])
    for hit in privacy_hits(text):
        errs.append("privacy: date-like or forbidden text in llms.txt -> " + hit)
    words = len(text.split())
    if words > MAX_WORDS:
        warns.append(f"llms.txt is {words} words; aim for under {MAX_WORDS}")
    return errs, warns


def build(args):
    manifest = json.loads((MD_DIR / "manifest.json").read_text(encoding="utf-8"))
    pages = manifest["pages"]
    u = urlsplit(pages[0]["url"])
    origin = f"{u.scheme}://{u.netloc}"
    order = sorted(pages, key=lambda p: (p["output"] != "index.md", p["output"]))
    text = SRC.read_text(encoding="utf-8")
    errs, warns = validate(text, pages, origin)
    out, notes = {}, []
    full = [
        "# " + re.sub(r"^# ", "", text.splitlines()[0]) + " - complete site text",
        "",
        "> Every page of "
        + origin
        + " in one file, generated from the Markdown pages. Start with "
        + origin
        + "/llms.txt for the guided overview.",
        "",
    ]
    for p in order:
        body = split_front((MD_DIR / p["output"]).read_text(encoding="utf-8")).strip()
        for hit in privacy_hits(body):
            notes.append(
                f"{p['output']}: date-like text '{hit}' (review the HTML copy)"
            )
        full += [
            "---",
            "",
            f"Source: {p['url']}  (Markdown: {p['markdown_url']})",
            "",
            body,
            "",
        ]
    out[MD_DIR / "llms.txt"] = text if text.endswith("\n") else text + "\n"
    out[MD_DIR / "llms-full.txt"] = "\n".join(full).rstrip() + "\n"
    ht = [
        "# Paste into seo/htaccess (generated by build-llms.py)",
        "<IfModule mod_mime.c>",
        "    AddType text/markdown .md",
        "    AddCharset UTF-8 .md .txt",
        "</IfModule>",
        "<IfModule mod_deflate.c>",
        "    AddOutputFilterByType DEFLATE text/markdown",
        "</IfModule>",
        "<IfModule mod_headers.c>",
    ]
    for p in order:
        name = Path(p["output"]).name
        ht += [
            f'    <Files "{name}">',
            f'        Header set Link "<{p["url"]}>; rel=\\"canonical\\", <{origin}/llms.txt>; rel=\\"describedby\\""',
            "    </Files>",
        ]
    ht += [
        "    # Optional privacy: hide file modification dates on every response",
        "    # Header unset Last-Modified",
        "    # Header unset ETag",
        "</IfModule>",
        "",
    ]
    heads = []
    for p in order:
        tags = [
            f'<link rel="alternate" type="text/markdown" href="{p["markdown_url"]}">',
            f'<link rel="describedby" href="{origin}/llms.txt">',
        ]
        heads += [f"<!-- {p['source']} -->"] + tags + [""]
        html = (
            (ROOT / p["source"]).read_text(encoding="utf-8")
            if (ROOT / p["source"]).exists()
            else ""
        )
        if not html:
            notes.append(
                p["source"] + ": source HTML not found; head-link check skipped"
            )
        elif not all(t.split(" href=")[1] in html for t in tags):
            notes.append(
                p["source"]
                + ": add the two <link> tags from build/reports/head-links.txt"
            )
    out[REPORTS / "htaccess-markdown.conf"] = "\n".join(ht)
    out[REPORTS / "head-links.txt"] = "\n".join(heads)
    for w in warns:
        print("WARN  " + w)
    for n in notes:
        print("NOTE  " + n)
    if errs:
        print("\nBUILD FAILED; nothing written", file=sys.stderr)
        for e in errs:
            print("  ERROR " + e, file=sys.stderr)
        return 2
    stale = 0
    for path, content in out.items():
        same = path.exists() and path.read_text(encoding="utf-8") == content
        print(("SAME  " if same else "WRITE ") + str(path.relative_to(ROOT)))
        if not same:
            stale += 1
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    print(
        f"\n{len(pages)} pages, llms-full.txt {len(out[MD_DIR / 'llms-full.txt'].split())} words, {len(notes)} note(s)."
    )
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if outputs are stale",
    )
    sys.exit(build(ap.parse_args()))
